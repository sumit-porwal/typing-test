export function getRandomWords(count = 25, options = {}) {
  const { punctuation = false, numbers = false, dictionary = 'standard' } = options;

  let pool = WORD_BANK;
  if (dictionary === 'expanded') pool = EXPANDED_WORD_BANK;
  if (dictionary === 'code') pool = CODE_WORD_BANK;

  const punctuationMarks = ['.', ',', '!', '?', ';'];
  const words = [];

  for (let i = 0; i < count; i++) {
    // Occasionally inject a number if numbers option is active
    if (numbers && Math.random() < 0.16) {
      const num = Math.floor(Math.random() * 900) + 10;
      words.push(String(num));
      continue;
    }

    let word = pool[Math.floor(Math.random() * pool.length)];

    if (punctuation) {
      // Capitalize first word or word after punctuation
      if (i === 0 || (i > 0 && ['.', '!', '?'].some(p => words[i - 1].endsWith(p)))) {
        word = word.charAt(0).toUpperCase() + word.slice(1);
      }
      // Add punctuation mark to every 4th to 6th word
      if (i < count - 1 && Math.random() < 0.22) {
        const mark = punctuationMarks[Math.floor(Math.random() * punctuationMarks.length)];
        word += mark;
      }
    }

    words.push(word);
  }

  // Ensure last word has a period if punctuation is enabled
  if (punctuation && words.length > 0) {
    const lastIdx = words.length - 1;
    if (!['.', '!', '?'].some(p => words[lastIdx].endsWith(p))) {
      words[lastIdx] += '.';
    }
  }

  return words.join(' ');
}

export function generateWeakKeyDrill(missedKeys = [], wordCount = 20) {
  if (!missedKeys || missedKeys.length === 0) {
    return getRandomWords(wordCount);
  }

  // Clean missed keys (ignore spaces)
  const cleanKeys = missedKeys.filter(k => k && k.trim().length > 0).map(k => k.toLowerCase());
  if (cleanKeys.length === 0) return getRandomWords(wordCount);

  // Find words in EXPANDED_WORD_BANK that contain any of the missed keys
  const targetWords = EXPANDED_WORD_BANK.filter(w =>
    cleanKeys.some(k => w.toLowerCase().includes(k))
  );

  const pool = targetWords.length >= 8 ? targetWords : [...targetWords, ...WORD_BANK];
  const result = [];

  for (let i = 0; i < wordCount; i++) {
    const chosen = pool[Math.floor(Math.random() * pool.length)];
    result.push(chosen);
  }

  return result.join(' ');
}

export function getRandomQuote() {
  const item = QUOTES[Math.floor(Math.random() * QUOTES.length)];
  return item.quote;
}
